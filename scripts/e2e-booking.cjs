// Verificação ponta a ponta do agendamento (servidor em :3000): node scripts/e2e-booking.cjs <pasta-screenshots>
const { chromium } = require('playwright')
const out = process.argv[2]
;(async () => {
  const browser = await chromium.launch()
  const ctx = await browser.newContext({ viewport: { width: 375, height: 812 }, deviceScaleFactor: 1 })
  const page = await ctx.newPage()
  page.on('pageerror', (e) => console.log('PAGEERROR', e.message))
  await page.goto('http://localhost:3000/')
  await page.screenshot({ path: `${out}/0-home.png`, fullPage: true })
  await page.getByRole('link', { name: 'Agendar horário' }).click()
  await page.getByRole('button', { name: /Corte\s*30 min/ }).first().click()
  await page.screenshot({ path: `${out}/1-barbeiro.png` })
  await page.getByRole('button', { name: /Rafael/ }).click()
  await page.getByRole('button', { name: /^\d\d:\d\d$/ }).first().waitFor({ timeout: 15000 })
  await page.screenshot({ path: `${out}/2-horario.png`, fullPage: true })
  const slot = page.getByRole('button', { name: /^\d\d:\d\d$/ }).last()
  const label = await slot.textContent()
  await slot.click()
  await page.waitForURL(/t=/)
  const url = page.url()
  await page.getByLabel('Nome').fill('Cliente Playwright')
  await page.getByLabel('WhatsApp com DDD').fill('(11) 9' + String(Date.now()).slice(-8))
  await page.screenshot({ path: `${out}/3-dados.png`, fullPage: true })
  await page.getByRole('button', { name: 'Confirmar agendamento' }).click()
  await page.getByRole('heading', { name: 'Horário confirmado' }).waitFor({ timeout: 15000 })
  await page.screenshot({ path: `${out}/4-confirmado.png`, fullPage: true })
  console.log('BOOKED', label, url)
  // segunda aba tenta o mesmo horário
  const p2 = await ctx.newPage()
  await p2.goto(url)
  await p2.getByLabel('Nome').fill('Outro Cliente')
  await p2.getByLabel('WhatsApp com DDD').fill('(11) 8' + String(Date.now()).slice(-8))
  await p2.getByRole('button', { name: 'Confirmar agendamento' }).click()
  const alert = await p2.getByText('Esse horário acabou de ser reservado').textContent({ timeout: 15000 })
  console.log('ALERT', alert)
  await p2.screenshot({ path: `${out}/5-ocupado.png`, fullPage: true })
  console.log('HREF', await page.getByRole('link', { name: 'Enviar confirmação no WhatsApp' }).getAttribute('href'))
  await browser.close()
})().catch((e) => { console.error(e); process.exit(1) })
